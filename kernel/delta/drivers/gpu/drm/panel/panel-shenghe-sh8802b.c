static void sh8802b_off_gpios(struct sh8802b *ctx)
{
	/* lcm_unprepare: reset low, bias 1 low, 1 ms, bias 0 low */
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
	gpiod_set_value_cansleep(ctx->bias_gpio[1], 0);
	usleep_range(1000, 1100);
	gpiod_set_value_cansleep(ctx->bias_gpio[0], 0);
}

static int sh8802b_off(struct sh8802b *ctx)
{
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };

	/* lcm_unprepare: 0x28, 50 ms, 0x10, 150 ms */
	mipi_dsi_dcs_set_display_off_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 50);
	mipi_dsi_dcs_enter_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 150);

	sh8802b_off_gpios(ctx);

	return dsi_ctx.accum_err;
}

static int sh8802b_on(struct sh8802b *ctx)
{
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };
	const u8 *p = sh8802b_init_table;

	/* lcm_prepare: bias 0 high, 2 ms, bias 1 high */
	gpiod_set_value_cansleep(ctx->bias_gpio[0], 1);
	usleep_range(2000, 2100);
	gpiod_set_value_cansleep(ctx->bias_gpio[1], 1);

	/* lcm_panel_init: reset high, low 15 ms, high 1 ms, low 10 ms, high 10 ms */
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
	usleep_range(15000, 15100);
	gpiod_set_value_cansleep(ctx->reset_gpio, 0);
	usleep_range(1000, 1100);
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
	usleep_range(10000, 10100);
	gpiod_set_value_cansleep(ctx->reset_gpio, 0);
	usleep_range(10000, 10100);

	while (*p && !dsi_ctx.accum_err) {
		u8 len = *p++;

		if (p[0] < 0xb0)
			mipi_dsi_dcs_write_buffer_multi(&dsi_ctx, p, len);
		else
			mipi_dsi_generic_write_multi(&dsi_ctx, p, len);
		p += len;
	}

	mipi_dsi_dcs_set_tear_on_multi(&dsi_ctx, MIPI_DSI_DCS_TEAR_MODE_VBLANK);
	mipi_dsi_dcs_exit_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 200);
	mipi_dsi_dcs_set_display_on_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 10);

	return dsi_ctx.accum_err;
}

