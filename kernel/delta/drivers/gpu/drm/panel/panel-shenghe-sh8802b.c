/*
 * Shenghe SH8802B AMOLED panel (1080x2340, MIPI DSI command mode, 4 lanes),
 * as fitted to the Planet Computers Astro Slide 5G.
 *
 * Every command, value, packet type, order and delay is the stock Android
 * kernel's (Planet 4.14 BSP drivers/gpu/drm/panel/panel-sh8802b-vdo.c,
 * lcm_prepare / lcm_panel_init / lcm_unprepare / lcm_setbacklight_cmdq);
 * see docs/display-stock.md in astro-linux618. There is no other path to
 * the panel: the init table below is the only manufacturer data sent, and
 * the only variable byte is the brightness (DCS 0x51, clamped to 0x3ff).
 * No command that the vendor driver does not send (OTP/MTP, HBM, AOD, deep
 * standby, soft reset) is present.
 *
 * The bootloader initialises the panel on every boot. As the vendor driver,
 * this driver takes it over as it is: the first prepare sends nothing.
 */

